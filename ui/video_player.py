def format_time(ms: int) -> str:
    """Milliseconds as m:ss."""
    seconds = max(0, int(ms) // 1000)
    return f"{seconds // 60}:{seconds % 60:02d}"


def control_icon(kind: str, color: QColor, size: int = 16) -> QIcon:
    """Crisp vector icons for the transport buttons ("back", "forward", "fullscreen", "exit_fullscreen")."""
    scale = 2  # draw at 2x for high-DPI screens
    pix = QPixmap(size * scale, size * scale)
    pix.fill(Qt.GlobalColor.transparent)
    p = QPainter(pix)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.scale(scale, scale)
    s = float(size)
    if kind in ("back", "forward"):
        p.setPen(Qt.PenStyle.NoPen)
        p.setBrush(color)
        for offset in (0.0, s * 0.42):
            tri = [QPointF(offset + s * 0.08, s * 0.2), QPointF(offset + s * 0.5, s * 0.5), QPointF(offset + s * 0.08, s * 0.8)]
            if kind == "back":
                tri = [QPointF(s - pt.x(), pt.y()) for pt in tri]
            p.drawPolygon(QPolygonF(tri))
    else:
        p.setPen(QPen(color, 1.6, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap, Qt.PenJoinStyle.RoundJoin))
        lo, hi, arm = s * 0.18, s * 0.82, s * 0.24
        inward = kind == "exit_fullscreen"
        for cx, cy, dx, dy in ((lo, lo, 1, 1), (hi, lo, -1, 1), (lo, hi, 1, -1), (hi, hi, -1, -1)):
            if inward:  # corners point toward the centre
                cx, cy = cx + dx * arm, cy + dy * arm
                dx, dy = -dx, -dy
            p.drawPolyline(QPolygonF([QPointF(cx, cy + dy * arm), QPointF(cx, cy), QPointF(cx + dx * arm, cy)]))
    p.end()
    return QIcon(pix)


