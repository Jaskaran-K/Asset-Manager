    def _update_controls_enabled(self, enabled: bool) -> None:
        for widget in (self.btn_play, self.btn_back, self.btn_forward, self.slider_seek):
            widget.setEnabled(enabled)
        if not enabled:
            self._hide_preview()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def load(self, path: str | Path, autoplay: bool = False) -> None:
        """Open a video file (replacing whatever was loaded)."""
        self._cancel_proxy_job()
        self._source = Path(path)
        self._using_proxy = False
        self._set_proxy_button(False)
        self._open(self._source, autoplay)

    def toggle(self) -> None:
        """Play if paused or stopped, otherwise pause."""
        if self.player.playbackState() == QMediaPlayer.PlaybackState.PlayingState:
            self.player.pause()
            return
        if self.player.mediaStatus() == QMediaPlayer.MediaStatus.EndOfMedia:
            self.player.setPosition(0)
        self.player.play()

    def skip(self, direction: int) -> None:
        """Jump back (-1) or forward (+1) by the selected jump time."""
        if not self.slider_seek.isEnabled():
            return
        target = self.player.position() + direction * self._skip_ms
        self.player.setPosition(max(0, min(self.player.duration(), target)))

    def stop(self) -> None:
        """Stop playback, cancel any proxy job and release the file handles."""
        self.set_fullscreen(False)
        self._cancel_proxy_job()
        self.player.stop()
        self.player.setSource(QUrl())
        self._preview_frames.release()
        self._update_controls_enabled(False)

    def is_fullscreen(self) -> bool:
        return self._fullscreen

    def set_fullscreen(self, enabled: bool) -> None:
        """Enter or leave fullscreen playback.

        A top-level player handles this itself; an embedded one emits
        fullscreen_changed so the host window can go fullscreen around it.
        """
        if enabled == self._fullscreen:
            return
        self._fullscreen = enabled
        self.btn_fullscreen.setIcon(self._icons["exit_fullscreen" if enabled else "fullscreen"])
        self.btn_fullscreen.setToolTip(
            "Exit fullscreen (Esc, F or double-click)" if enabled else "Fullscreen (F or double-click the video)"
        )
        if self.isWindow():
            self.showFullScreen() if enabled else self.showNormal()
        self.fullscreen_changed.emit(enabled)
        if enabled:
            self._wake_controls()
        else:
            self._hide_timer.stop()
            self._show_controls()
        self.setFocus()

    def closeEvent(self, event) -> None:
        self.stop()
        super().closeEvent(event)

    def hideEvent(self, event) -> None:
        self._hide_preview()
        super().hideEvent(event)

    def keyPressEvent(self, event) -> None:
        if not self._handle_key(event):
            super().keyPressEvent(event)

    def _handle_key(self, event) -> bool:
        """Player keys (see ui.shortcuts). Returns True if the key was used."""
        if shortcuts.matches("video.play_pause", event) and self.btn_play.isEnabled():
            self.toggle()
        elif shortcuts.matches("video.back", event):
            self.skip(-1)
        elif shortcuts.matches("video.forward", event):
            self.skip(1)
        elif shortcuts.matches("video.fullscreen", event):
            self.set_fullscreen(not self._fullscreen)
        elif shortcuts.matches("video.exit_fullscreen", event) and self._fullscreen:
            self.set_fullscreen(False)
        else:
            return False
        self._wake_controls()
        return True

    def eventFilter(self, obj: QObject, event: QEvent) -> bool:
        etype = event.type()
        if etype == QEvent.Type.MouseMove:
            if self._fullscreen:
                self._wake_controls()
        elif etype == QEvent.Type.MouseButtonDblClick:
            if self._cursor_over_video():
                self.set_fullscreen(not self._fullscreen)
                return True
        elif etype == QEvent.Type.KeyPress and self._is_video_window(obj):
            # Clicking the video gives its native window keyboard focus; keep the shortcuts working
            return self._handle_key(event)
        return False

    def _is_video_window(self, obj: QObject) -> bool:
        """True for the native child window that draws the video inside this player's window."""
        if not isinstance(obj, QWindow) or obj.parent() is None:
            return False  # widgets, top-level windows and popups handle their own keys
        top = self.window().windowHandle()
        ancestor = obj.parent()
        while ancestor is not None and ancestor is not top:
            ancestor = ancestor.parent()
        return ancestor is top and top is not None

    def _cursor_over_video(self) -> bool:
        if self.stack.currentIndex() != self._PAGE_VIDEO or not self.video_widget.isVisible():
            return False
        if QApplication.activeWindow() is not self.window():
            return False
        return self.video_widget.rect().contains(self.video_widget.mapFromGlobal(QCursor.pos()))

    # ------------------------------------------------------------------
    # Fullscreen controls auto-hide
    # ------------------------------------------------------------------
    def _wake_controls(self) -> None:
        if not self._fullscreen:
            return
        self._show_controls()
        self._hide_timer.start()

    def _show_controls(self) -> None:
        self.controls.show()
        if self._cursor_hidden:
            self._cursor_hidden = False
            QApplication.restoreOverrideCursor()

    def _hide_controls_if_idle(self) -> None:
        playing = self.player.playbackState() == QMediaPlayer.PlaybackState.PlayingState
        over_controls = self.controls.rect().contains(self.controls.mapFromGlobal(QCursor.pos()))
        if not self._fullscreen or not playing or over_controls or self.slider_seek.isSliderDown():
            self._hide_timer.start()
            return
        self._hide_preview()
        self.controls.hide()
        if not self._cursor_hidden:
            self._cursor_hidden = True
            QApplication.setOverrideCursor(Qt.CursorShape.BlankCursor)

    # ------------------------------------------------------------------
    # Playback
    # ------------------------------------------------------------------
    def _open(self, path: Path, autoplay: bool, position: int = 0) -> None:
        self.player.stop()
        # Set after stop(): stopping the previous file reports LoadedMedia, which would consume it
        self._failed = False
        self._resume_position = position
        self._update_controls_enabled(False)
        self.slider_seek.setRange(0, 0)
        self.lbl_time.setText("0:00 / 0:00")
        self.stack.setCurrentIndex(self._PAGE_VIDEO)
        self.lbl_proxy.setVisible(self._using_proxy)
        # Hover previews decode whichever file is actually playing (original or proxy)
        self._preview_frames.set_source(path)
        # fromLocalFile handles spaces and non-ASCII characters in Windows paths
        self.player.setSource(QUrl.fromLocalFile(str(path)))
        if autoplay:
            self.player.play()

    def _on_position_changed(self, position: int) -> None:
        # Don't fight the user while they're dragging the handle
        if not self.slider_seek.isSliderDown():
            self.slider_seek.setValue(position)
        self._update_time_label(position)

    def _on_duration_changed(self, duration: int) -> None:
        self.slider_seek.setRange(0, max(0, duration))
        self.slider_seek.setPageStep(self._skip_ms)
        self._update_time_label(self.player.position())

    def _update_time_label(self, position: int) -> None:
        self.lbl_time.setText(f"{format_time(position)} / {format_time(self.player.duration())}")

    def _on_seek_requested(self, value: int) -> None:
        self.player.setPosition(value)
        self._update_time_label(value)

    def _on_seek_hover(self, value: int, x: int) -> None:
        self._hover_value = value
        self._preview_popup.set_frame(self._preview_frames.cached(value))
        self._preview_popup.show_above(self.slider_seek, x, value)
        if self._preview_frames.cached(value) is None:
            self._preview_frames.request(value)

    def _on_preview_frame(self, position: int, image: QImage) -> None:
        if self._hover_value is not None and self._preview_popup.isVisible():
            # Show the newest decoded frame; a closer one follows if the mouse kept moving
            cached = self._preview_frames.cached(self._hover_value)
            self._preview_popup.set_frame(cached if cached is not None else image)

    def _hide_preview(self) -> None:
        self._hover_value = None
        self._preview_popup.hide()

    def _on_skip_changed(self, _index: int) -> None:
        seconds = self.cb_skip.currentData()
        self._skip_ms = seconds * 1000
        self.slider_seek.setPageStep(self._skip_ms)
        set_video_skip_seconds(seconds)
        self._update_skip_tooltips()

    def _update_skip_tooltips(self) -> None:
        seconds = self._skip_ms // 1000
        self.btn_back.setToolTip(f"Back {seconds} s (Left arrow)")
        self.btn_forward.setToolTip(f"Forward {seconds} s (Right arrow)")

    def _on_state_changed(self, state: QMediaPlayer.PlaybackState) -> None:
        playing = state == QMediaPlayer.PlaybackState.PlayingState
        self.btn_play.setText("⏸ Pause" if playing else "▶ Play")
        if not playing:
            self._show_controls()  # keep controls visible while paused in fullscreen

    def _on_volume_changed(self, value: int) -> None:
        global _last_volume
        _last_volume = value
        self.audio.setVolume(value / 100.0)

    def _on_media_status_changed(self, status: QMediaPlayer.MediaStatus) -> None:
        if status == QMediaPlayer.MediaStatus.LoadedMedia:
            if not self.player.hasVideo():
                # Unsupported codecs often "load" fine and then render black
                self._fail("No playable video stream was found. The codec is probably not supported.")
                return
            self._update_controls_enabled(True)
            if self._resume_position:
                self.player.setPosition(self._resume_position)
                self._resume_position = 0
        elif status == QMediaPlayer.MediaStatus.InvalidMedia:
            self._fail(self.player.errorString() or "The file couldn't be opened.")

    def _on_player_error(self, error: QMediaPlayer.Error, message: str) -> None:
        if error != QMediaPlayer.Error.NoError:
            self._fail(message or str(error.name))

    def _fail(self, message: str) -> None:
        if self._failed:  # errorOccurred and InvalidMedia often arrive together
            return
        self._failed = True
        self.player.stop()
        self._update_controls_enabled(False)
        self._preview_frames.set_source(None)
        self.error_occurred.emit(message)

        if self._using_proxy or not self._enable_proxy:
            self._show_message("Can't play this video", message)
            return
        # A proxy made earlier is cheap to fall back on, so use it straight away
        proxy = cached_proxy(self._source) if self._source is not None else None
        if proxy is not None:
            self._set_proxy_button(True)
            # Deferred so the failed file's remaining error signals land while _failed is still set
            source = self._source
            QTimer.singleShot(0, lambda: self._source == source and self._play_proxy(proxy, autoplay=True))
            return
        self._show_message(
            "Can't play this video",
            f"{message}\n\nGenerate a {PROXY_HEIGHT}p H.264 preview copy with ffmpeg and play that instead?"
            + self._ffmpeg_missing_note(),
            offer_proxy=find_ffmpeg() is not None,
        )

    # ------------------------------------------------------------------
    # Proxy fallback
    # ------------------------------------------------------------------
    @staticmethod
    def _ffmpeg_missing_note() -> str:
        if find_ffmpeg() is not None:
            return ""
        return (
            "\n\nffmpeg wasn't found. Install it (for example: winget install ffmpeg) "
            "or set its location in Settings > Video, then reopen this video."
        )

    def _set_proxy_button(self, checked: bool) -> None:
        self.btn_proxy.blockSignals(True)
        self.btn_proxy.setChecked(checked)
        self.btn_proxy.blockSignals(False)

    def _on_proxy_toggled(self, checked: bool) -> None:
        if self._source is None:
            return
        position = self.player.position()
        if not checked:
            self._cancel_proxy_job()
            self._using_proxy = False
            self._open(self._source, autoplay=True, position=position)
            return
        proxy = cached_proxy(self._source)
        if proxy is not None:
            self._play_proxy(proxy, autoplay=True, position=position)
        else:
            self._start_proxy()

    def _play_proxy(self, proxy: Path, autoplay: bool, position: int = 0) -> None:
        self._using_proxy = True
        self._open(proxy, autoplay, position)

    def _start_proxy(self) -> None:
        if self._source is None or self._proxy_job is not None:
            return
        ffmpeg = find_ffmpeg()
        if ffmpeg is None:
            self._set_proxy_button(False)
            self._show_message("ffmpeg not found", self._ffmpeg_missing_note().strip())
            return
        self.player.stop()
        self.player.setSource(QUrl())  # release the file while ffmpeg reads it
        self._preview_frames.set_source(None)
        self._update_controls_enabled(False)
        self._set_proxy_button(True)
        self.progress.setRange(0, 0)  # busy until ffmpeg reports the duration
        self._show_message(
            "Generating preview...",
            f"Converting to {PROXY_HEIGHT}p H.264 in the background. It's cached, so this only happens once per file.",
            busy=True,
        )
        job = ProxyJob(self._source, self)
        job.progress.connect(self._on_proxy_progress)
        job.finished.connect(self._on_proxy_finished)
        job.failed.connect(self._on_proxy_failed)
        self._proxy_job = job
        job.start(ffmpeg)

    def _on_proxy_progress(self, fraction: float) -> None:
        if fraction < 0:
            return
        if self.progress.maximum() == 0:
            self.progress.setRange(0, 100)
        self.progress.setValue(int(fraction * 100))

    def _on_proxy_finished(self, proxy: str) -> None:
        self._drop_proxy_job()
        self._play_proxy(Path(proxy), autoplay=True)

    def _on_proxy_failed(self, message: str) -> None:
        self._drop_proxy_job()
        self._set_proxy_button(False)
        self.error_occurred.emit(message)
        self._show_message("Preview generation failed", message)

    def _on_cancel_proxy(self) -> None:
        self._cancel_proxy_job()
        self._set_proxy_button(False)
        if self._source is not None:
            self._using_proxy = False
            self._open(self._source, autoplay=False)

    def _drop_proxy_job(self) -> None:
        if self._proxy_job is not None:
            self._proxy_job.deleteLater()
            self._proxy_job = None

    def _cancel_proxy_job(self) -> None:
        if self._proxy_job is not None:
            self._proxy_job.cancel()
            self._drop_proxy_job()


