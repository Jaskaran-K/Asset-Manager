class SeekSlider(QSlider):
    """Horizontal slider that jumps to the clicked point and reports hover positions."""

    seek_requested = Signal(int)  # value the user clicked or dragged to
    hover_changed = Signal(int, int)  # value, x position (widget coordinates) to preview
    hover_ended = Signal()

    def __init__(self, parent: Optional[QWidget] = None):
        super().__init__(Qt.Orientation.Horizontal, parent)
        self.setMouseTracking(True)
        self.sliderMoved.connect(self._on_dragged)
        self.sliderReleased.connect(self._on_released)

    def _groove_metrics(self) -> tuple[int, int, int]:
        """(groove start x, usable span, handle width) for value <-> pixel conversion."""
        opt = QStyleOptionSlider()
        self.initStyleOption(opt)
        style = self.style()
        groove = style.subControlRect(QStyle.ComplexControl.CC_Slider, opt, QStyle.SubControl.SC_SliderGroove, self)
        handle = style.subControlRect(QStyle.ComplexControl.CC_Slider, opt, QStyle.SubControl.SC_SliderHandle, self)
        return groove.x(), max(1, groove.width() - handle.width()), handle.width()

    def value_at(self, x: int) -> int:
        start, span, handle_w = self._groove_metrics()
        return QStyle.sliderValueFromPosition(self.minimum(), self.maximum(), int(x - start - handle_w / 2), span)

    def x_for(self, value: int) -> int:
        start, span, handle_w = self._groove_metrics()
        return start + int(handle_w / 2) + QStyle.sliderPositionFromValue(self.minimum(), self.maximum(), value, span)

    def mousePressEvent(self, event) -> None:
        if event.button() == Qt.MouseButton.LeftButton and self.maximum() > self.minimum():
            # Jump to the click, then let QSlider start a drag from there (the handle is now under the cursor)
            value = self.value_at(int(event.position().x()))
            self.setValue(value)
            self.seek_requested.emit(value)
            self.hover_changed.emit(value, self.x_for(value))
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event) -> None:
        super().mouseMoveEvent(event)
        if self.maximum() <= self.minimum():
            return
        if self.isSliderDown():
            value = self.sliderPosition()
            self.hover_changed.emit(value, self.x_for(value))
        else:
            x = int(event.position().x())
            self.hover_changed.emit(self.value_at(x), x)

    def leaveEvent(self, event) -> None:
        if not self.isSliderDown():
            self.hover_ended.emit()
        super().leaveEvent(event)

    def _on_dragged(self, value: int) -> None:
        self.seek_requested.emit(value)

    def _on_released(self) -> None:
        self.seek_requested.emit(self.value())
        if not self.rect().contains(self.mapFromGlobal(QCursor.pos())):
            self.hover_ended.emit()


class _SeekPreviewPopup(QWidget):
    """Small frame + timestamp bubble shown above the seek bar."""

    def __init__(self, parent: QWidget):
        # Parented (so it's deleted with the player) but still its own floating window
        super().__init__(parent, Qt.WindowType.ToolTip | Qt.WindowType.FramelessWindowHint)
        self.setAttribute(Qt.WidgetAttribute.WA_ShowWithoutActivating)
        self.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
        self.setObjectName("seekPreview")
        layout = QVBoxLayout(self)
        layout.setContentsMargins(4, 4, 4, 4)
        layout.setSpacing(3)
        self.lbl_frame = QLabel()
        self.lbl_frame.setObjectName("seekPreviewFrame")
        self.lbl_frame.setFixedSize(PREVIEW_SIZE)
        self.lbl_frame.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.lbl_time = QLabel()
        self.lbl_time.setObjectName("seekPreviewTime")
        self.lbl_time.setAlignment(Qt.AlignmentFlag.AlignCenter)
        layout.addWidget(self.lbl_frame)
        layout.addWidget(self.lbl_time)
        self.adjustSize()

    def set_frame(self, image: Optional[QImage]) -> None:
        if image is None or image.isNull():
            self.lbl_frame.clear()
        else:
            self.lbl_frame.setPixmap(QPixmap.fromImage(image))

    def show_above(self, slider: QWidget, x: int, time_ms: int) -> None:
        self.lbl_time.setText(format_time(time_ms))
        anchor = slider.mapToGlobal(QPoint(x, 0))
        pos = QPoint(anchor.x() - self.width() // 2, anchor.y() - self.height() - 6)
        screen = slider.screen().availableGeometry() if slider.screen() else None
        if screen is not None:
            pos.setX(max(screen.left(), min(pos.x(), screen.right() - self.width())))
            pos.setY(max(screen.top(), pos.y()))
        self.move(pos)
        if not self.isVisible():
            self.show()
        self.raise_()


class _PreviewFrameSource(QObject):
    """Decodes preview frames with a silent, paused QMediaPlayer.

    Only one seek is in flight at a time; while it decodes, newer requests
    replace the pending one, so fast mouse movement never queues up seeks.
    Frames are cached per half-second so hovering back is instant.
    """

    frame_ready = Signal(int, QImage)  # requested position, scaled frame

    _CACHE_LIMIT = 150
    _BUCKET_MS = 500

    def __init__(self, parent: Optional[QObject] = None):
        super().__init__(parent)
        self._player: Optional[QMediaPlayer] = None
        self._sink: Optional[QVideoSink] = None
        self._path: Optional[Path] = None
        self._loaded_path: Optional[Path] = None
        self._pending: Optional[int] = None
        self._in_flight: Optional[int] = None
        self._cache: OrderedDict[int, QImage] = OrderedDict()
        self._watchdog = QTimer(self)
        self._watchdog.setSingleShot(True)
        self._watchdog.setInterval(800)
        self._watchdog.timeout.connect(self._on_watchdog)

    def set_source(self, path: Optional[Path]) -> None:
        """Remember the file to preview (opened lazily on the first request)."""
        if path != self._path:
            self._path = path
            self._cache.clear()
            self._pending = self._in_flight = None
            if self._player is not None:
                self._player.setSource(QUrl())
                self._loaded_path = None

    def release(self) -> None:
        self._watchdog.stop()
        self._pending = self._in_flight = None
        self._path = None
        if self._player is not None:
            self._player.stop()
            self._player.setSource(QUrl())
        self._loaded_path = None
        self._cache.clear()

    def cached(self, position: int) -> Optional[QImage]:
        return self._cache.get(position // self._BUCKET_MS)

    def request(self, position: int) -> None:
        if self._path is None:
            return
        if self._player is None:
            self._player = QMediaPlayer(self)  # no audio output: silent
            self._sink = QVideoSink(self)
            self._player.setVideoSink(self._sink)
            self._sink.videoFrameChanged.connect(self._on_frame)
            self._player.mediaStatusChanged.connect(self._on_status)
        if self._loaded_path != self._path:
            self._loaded_path = self._path
            self._player.setSource(QUrl.fromLocalFile(str(self._path)))
            self._player.pause()  # paused players still decode a frame after each seek
        self._pending = position
        self._seek_next()

    def _media_ready(self) -> bool:
        return self._player is not None and self._player.mediaStatus() in (
            QMediaPlayer.MediaStatus.LoadedMedia,
            QMediaPlayer.MediaStatus.BufferedMedia,
            QMediaPlayer.MediaStatus.BufferingMedia,
            QMediaPlayer.MediaStatus.EndOfMedia,
        )

    def _seek_next(self) -> None:
        if self._in_flight is not None or self._pending is None or not self._media_ready():
            return
        self._in_flight, self._pending = self._pending, None
        self._watchdog.start()
        self._player.setPosition(self._in_flight)

    def _on_status(self, _status) -> None:
        self._seek_next()

    def _on_frame(self, frame: QVideoFrame) -> None:
        if self._in_flight is None or not frame.isValid():
            return
        requested, self._in_flight = self._in_flight, None
        self._watchdog.stop()
        image = frame.toImage()
        if not image.isNull():
            image = image.scaled(
                PREVIEW_SIZE, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation
            )
            self._cache[requested // self._BUCKET_MS] = image
            while len(self._cache) > self._CACHE_LIMIT:
                self._cache.popitem(last=False)
            self.frame_ready.emit(requested, image)
        self._seek_next()

    def _on_watchdog(self) -> None:
        # Some seeks (e.g. to the very end) never produce a frame; don't stall the queue
        self._in_flight = None
        self._seek_next()


