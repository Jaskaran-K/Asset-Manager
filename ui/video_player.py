"""Reusable in-app video player built on Qt Multimedia (QMediaPlayer).

Qt 6.5+ decodes through its bundled FFmpeg backend on Windows; the Windows
Media Foundation backend can be chosen in Settings > Video or with the
QT_MEDIA_BACKEND environment variable (see core.video_tools.apply_media_backend).

Files QMediaPlayer can't decode (often pro codecs, which tend to fail as a
silent black frame) or that stutter (high-bitrate 4K) can be played through a
cached 720p H.264 proxy generated by ffmpeg in the background.

Seek bar: click anywhere to jump there; hovering or dragging shows a preview
frame, decoded by a second, silent QMediaPlayer that seeks on demand.

Fullscreen: when the player is a top-level window it goes fullscreen itself;
when embedded, it emits fullscreen_changed and the host window (e.g. the
asset viewer dialog) hides its own chrome and goes fullscreen.

Known limitations (by design for now):
- Seeking snaps to keyframes on long-GOP footage, so it isn't frame-accurate
  (this applies to the hover preview frames as well).
- QMediaPlayer has no frame-step API. A rough workaround is to pause and call
  setPosition(position + 1000 / fps).
- If frame-accurate scrubbing or broad pro-codec support is needed later, the
  upgrade path is python-mpv (libmpv embedded via winId(), shipping
  libmpv-2.dll) rather than more work on QMediaPlayer.

Standalone demo:  python -m ui.video_player <video file>
"""

